import sys
"""
The sound of the Gion Shoja temple bells echoes the impermanence of all things; 
the color of the sala flowers reveals the truth that to flourish is to fall. 
The proud do not endure, like a passing dream on a night in spring; the mighty fall at last, 
to be no more than dust before the wind
"""
def run_battle():

    try:
        line = sys.stdin.readline()
        if not line:
            return
        num_test_cases = int(line.strip())
    except ValueError:
        return

    for _ in range(num_test_cases):
        # N = number of curses
        # P = Gojo's starting power
        # R = amount restored by RCT
        # K = curses needed for one RCT use
        try:
            params = sys.stdin.readline().split()
            if not params:
                break
            
            n_curses = int(params[0])
            current_power = int(params[1])
            restore_amount = int(params[2])
            kill_streak_needed = int(params[3])

            energies = sys.stdin.readline().split()
        except (ValueError, IndexError):
            break

        defeated_streak = 0
        is_defeated = False

        for energy_str in energies:
            energy_cost = int(energy_str)
            
            # 1. THE CURSE EVERYBODY INVITED
            current_power -= energy_cost

            if current_power < 0:
                is_defeated = True
                break
            
            defeated_streak += 1

            if defeated_streak == kill_streak_needed:
                current_power += restore_amount
                defeated_streak = 0 

        if is_defeated:
            print("nah i'd lose")
        else:
            print("nah i'd win")

if __name__ == "__main__":
    run_battle()


