import sys

data = sys.stdin.read().split()

def Kurourishi():
    if not data: return
    
    total_test_cases = int(data[0])
    idx = 1
    
    for _ in range(total_test_cases):
        n_floors = int(data[idx]); idx += 1
        
        top_tower = []
        height_sum = 0
        for i in range(n_floors):
            val = int(data[idx])
            top_tower.append(val)
            height_sum += val
            idx += 1
            
        # print(f"DEBUG: floors={n_floors} sum={height_sum}")

        avg_h = round(height_sum / n_floors)
        
        bottom_tower = []
        for j in range(n_floors):
            bottom_tower.append(str(avg_h))
            
        sys.stdout.write(" ".join(bottom_tower) + "\n")

if __name__ == "__main__":
    Kurourishi()



