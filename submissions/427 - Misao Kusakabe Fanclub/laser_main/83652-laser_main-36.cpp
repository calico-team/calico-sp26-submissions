#include <bits/stdc++.h>
using namespace std;
using ll = long long;

void solve(){
    ll i,k,n,m,p,q,x,y,xq,yq;
    map<pair<ll,ll>,ll>memo;
    cin >> k >> n >> m >> p >> q;
    for(i=0;i<k;i++){
        cin >> x >> y;
        memo[{x,y}]=i;
        if(i==0){
            xq=x;
            yq=y;
        }
    }
    while(1){
        xq+=q;
        yq+=p;
        if(xq>=n){
            xq-=n;
        }
        if(yq>=m){
            yq-=m;
        }
        if(memo.find({xq,yq})!=memo.end()){
            cout << memo[{xq,yq}] << endl;
            return;
        }
    }
}
 
int main(){
    ios::sync_with_stdio(false);
    cin.tie(NULL);
    ll t=1;
    cin >> t;
    while(t--){
        solve();
    }
}
