#include <bits/stdc++.h>
using namespace std;

/*
 * M: number of rows in the lecture hall
 * N: number of columns in the lecture hall
 * K: number of friends who need seats
 * GRID: vector of M strings of length N; '#' is a blocked seat, '-' is an empty seat
 *
 * Return a vector of K (row, col) pairs for the chosen seats.
 */
vector<pair<int, int>> solve(int M, int N, int K, vector<string>& GRID) {
    // YOUR CODE HERE
    int s=M+N-1;
    vector<vector<array<int,3>>> b(s);
    for(int r=0;r<M;r++){
        for(int c=0;c<N;c++){
            if(GRID[r][c]=='-') b[r+c].push_back({r-c+N-1,r,c});
        }
    }
    vector<int> no(s);
    auto work=[&](int d)->pair<int,int>{
        fill(no.begin(),no.end(),0);
        for(int u=0;u<=d&&u<s;u++){
            for(auto [v,r,c]:b[u]) no[v]++;
        }
        for(int u=0;u<s;u++){
            int cur=0;
            for(int v=0;v<s;v++){
                cur+=no[v];
                if(v>d) cur-=no[v-d-1];
                if(v>=d&&cur>=K) return {u,v-d};
            }
            for(auto [v,r,c]:b[u]) no[v]--;
            if(u+d+1<s){
                for(auto [v,r,c]:b[u+d+1]) no[v]++;
            }
        }
        return {-1,-1};
    };
    int lo=0,hi=s-1;
    while(lo<hi){
        int md=(lo+hi)/2;
        if(work(md).first!=-1) hi=md;
        else lo=md+1;
    }
    auto [u,v]=work(lo);
    vector<pair<int,int>> ans;
    for(int i=u;i<=u+lo && i<s && ans.size()<K;i++){
        for(auto [j,r,c]:b[i]){
            if(v<=j&&j<=v+lo){
                ans.push_back({r,c});
                if(ans.size()==K) break;
            }
        }
    }
    return ans;
}

int main() {
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);

    int T;
    cin >> T;
    while (T--) {
        int M, N, K;
        cin >> M >> N >> K;
        vector<string> GRID(M);
        for (int i = 0; i < M; i++) {
            cin >> GRID[i];
        }
        vector<pair<int, int>> result = solve(M, N, K, GRID);
        for (auto& p : result) {
            cout << p.first << " " << p.second << "\n";
        }
    }
    return 0;
}
