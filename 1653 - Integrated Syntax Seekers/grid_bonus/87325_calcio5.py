import sys

input = sys.stdin.readline
sys.setrecursionlimit(200005) 

def Kurourushi_nahidsolve():
    s = input().split()
    if not s: return
    n = int(s[0])
    a = [int(x) for x in input().split()]

    if n == 1:
        print(a[0])
        return

    lo = [0] * n
    hi = [0] * n
    lo[0] = hi[0] = a[0]

    for i in range(1, n):
        prev_l, prev_r = lo[i-1], hi[i-1]
        cur = a[i]
        
        if cur < prev_l:
            lo[i], hi[i] = cur, prev_l

        elif cur > prev_r:
            lo[i], hi[i] = prev_r, cur

        else:
            lo[i] = hi[i] = cur

    res = [0] * n
    # go from the last element of the input 
    res[-1] = a[-1] 
    
    for j in range(n-2, -1, -1):
        target = res[j+1]
        l_bound, r_bound = lo[j], hi[j]
        
        if target < l_bound:
            res[j] = l_bound

        elif target > r_bound:
            res[j] = r_bound

        else:
            res[j] = target
            
    print(*(res))

line = input().split()
if line:
    
    t_cases = int(line[0])

    for _ in range(t_cases):
        Kurourushi_nahidsolve()

