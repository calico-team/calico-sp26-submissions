import sys

input = sys.stdin.readline

def Kurourushi_nahidsolve():
    s = input().split()
    if not s: return
    n = int(s[0])
    
    a = [int(x) for x in input().split()]

    if n == 1:
        print(a[0])
        return

# I LOVE THE TASTE OF IRON

    low = [0] * n
    high = [0] * n
    
    low[0] = high[0] = a[0]
    
    for i in range(1, n):
        if a[i] < low[i-1]:
            low[i], high[i] = a[i], low[i-1]

        elif a[i] > high[i-1]:
            low[i], high[i] = low[i-1], a[i]

        else:
            low[i] = high[i] = a[i]
            
    res = [0] * n
    res[-1] = low[-1]
    
    for j in range(n - 2, -1, -1):
        nxt = res[j+1]
        if nxt < low[j]:
            res[j] = low[j]

        elif nxt > high[j]:
            res[j] = high[j]

        else:
            res[j] = nxt
            
    print(*(res))

line = input().split()
if line:
    t = int(line[0])
    for _ in range(t):
        Kurourushi_nahidsolve()


