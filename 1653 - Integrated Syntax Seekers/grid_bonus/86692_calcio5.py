import sys
input = sys.stdin.readline

def Kurourushi_nahidsolve():
    try:
        line = input().split()
        if not line: return
        n = int(line[0])
        a = [int(x) for x in input().split()] 
    except Exception:
        return

    if n == 1:
        print(a[0])
        return

# I LOVE THE TASTE OF IRON
    
    d_sum = 0
    for i in range(n - 1):
        v = a[i] - a[i+1]
        if v < 0: v = -v
        d_sum += v
    
    #just copy top to bottom
    c1 = d_sum * 2 

    #move everything to median
    b = sorted(a)
    med = b[n // 2]
    
    v_cost = 0
    for x in a:
        tmp = x - med
        if tmp < 0: tmp = -tmp
        v_cost += tmp
    
    c2 = d_sum + v_cost

    # print(f"DEBUG: c1={c1} c2={c2}") 

    if c2 < c1:
        res = [med] * n
        print(*res)
    else:
        print(*a)

# main loop
line = input().split()
if line:
    for _ in range(int(line[0])):
        Kurourushi_nahidsolve()


