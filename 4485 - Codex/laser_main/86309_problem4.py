import math

def egcd(a, b):
    if b == 0:
        return a, 1, 0
    g, x, y = egcd(b, a % b)
    return g, y, x - (a // b) * y

def modinv(a, m):
    g, x, _ = egcd(a, m)
    if g != 1:
        return None
    return x % m

def crt(a, n, b, m):
    g, x, _ = egcd(n, m)
    if (b - a) % g != 0:
        return None, None
    lcm = n // g * m
    t = (a + (b - a) // g * x % (m // g) * n) % lcm
    return t, lcm

