#include <iostream>
#include <bits/stdc++.h>
#define endl '\n'
using namespace std;

string solve(string A, string B) {
    /*
    For each test case, output the result of redacting the initial string A.

    A: the initial string
    B: the target string
    */
    
    // YOUR CODE HERE

    string result;
    size_t pos = 0;

    for(char a: A){
        if(pos < B.size() && a == B[pos]){
            result.push_back(a);
            pos++;
        }

        else{
            result.push_back('#');
        }
    }
    return result;
}
 
