ll power(ll a, ll b) {
    ll result = 1;
    while(b) {
        if (b & 1) 
        result = result * a;
        a = a * a;
        b >>= 1;
    }
    return result;
}


ll modpow(ll a,ll k, ll m) // https://github.com/gcmwhite/mod_pow/blob/master/mod_pow.cpp
{
    ll b = 1;
    while (k >= 1)
    {
        if (k % 2 == 1)
        {
            b = a * b % m;
        }
        a = a * a % m;
        k = k / 2;
    }
    return b;
}

ll modinv(ll n, ll mod){ // https://usaco.guide/gold/modular
    return modpow(n, mod-2, mod);
}
