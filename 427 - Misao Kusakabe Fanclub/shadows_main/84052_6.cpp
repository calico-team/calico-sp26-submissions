void solve(){
    ll n; cin >> n;
    vector<vector<bool>> s1(n, vector<bool>(n, false));
    vector<vector<bool>> s2(n, vector<bool>(n, false));
    for (ll i=0;i<n;i++){
        string row; cin >> row;
        for (ll j=0;j<n;j++){
            s1[i][j]=row[j]=='#';
        }
    }
    for (ll i=0;i<n;i++){
        string row; cin >> row;
        for (ll j=0;j<n;j++){
            s2[i][j]=row[j]=='#';
        }
    }

    ll mnans = 0, mxans = 0;

    for (ll i=0;i<n;i++){
        ll c1 = 0, c2 = 0;
        for (ll j=0;j<n;j++){
            c1 += s1[i][j];
            c2 += s2[i][j];
        }
        mxans += c1*c2;
    }

    for (ll i=0;i<n;i++){
        ll c1 = 0, c2 = 0;
        for (ll j=0;j<n;j++){
            c1 += s1[i][j];
            c2 += s2[i][j];
        }
        mnans += max(c1,c2);
    }

    cout << mxans << ' ' << mnans << endl;
}
int main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    ll t; cin >> t;
    while (t--) solve();
}