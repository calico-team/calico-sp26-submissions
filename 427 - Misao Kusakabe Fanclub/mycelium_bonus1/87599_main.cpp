#include <bits/stdc++.h>
using namespace std;
using ll = long long;

vector<vector<bool>>grid(1600,vector<bool>(1600,false));
ll ans=1;
vector<ll> dx={1,-1,0,0};
vector<ll> dy={0,0,1,-1};

void bfs(ll xg,ll yg,ll xm,ll ym){
    queue<pair<ll,ll>>grass;
    queue<pair<ll,ll>>myc;
    queue<pair<ll,ll>>grasstemp;
    queue<pair<ll,ll>>myctemp;
    pair<ll,ll>node;
    grass.push({xg,yg});
    myc.push({xm,ym});
    ll timer=1,x,y;
    vector<vector<bool>>(1600,vector<bool>(1600,false)).swap(grid);
    grid[xg][yg]=true;
    grid[xm][ym]=true;
    while(1){
        if(timer%2==0){
            while(!grass.empty()){
                node=grass.front();
                grass.pop();
                for(ll i=0;i<4;i++){
                    x=node.first+dx[i];
                    y=node.second+dy[i];
                    if(grid[x][y]==false){
                        //cout << timer << " GRASS: " << x << " " << y << endl;
                        grid[x][y]=true;
                        grasstemp.push({x,y});
                    }
                }
            }
            grass.swap(grasstemp);
        }
        if(timer%7==0){
            while(!myc.empty()){
                node=myc.front();
                myc.pop();

                for(ll i=0;i<4;i++){
                    x=node.first+dx[i];
                    y=node.second+dy[i];
                    if(grid[x][y]==false){
                        //cout << timer << " MYC: " << x << " " << y << endl;
                        ans++;
                        grid[x][y]=true;
                        myctemp.push({x,y});
                    }
                }
            }
            if(myctemp.empty()){
                return;
            }
            myc.swap(myctemp);
        }
        timer++;
    }
}

void solve(){
    ios::sync_with_stdio(false);
    cin.tie(NULL),cout.tie(nullptr);
    ll xg,yg,xm,ym;
    cin >> xg >> yg >> xm >> ym;
    xg+=1000;
    yg+=1000;
    xm+=1000;
    ym+=1000;
    ans=1;
    bfs(xg,yg,xm,ym);
    cout << ans << endl;
}
 
int main(){
    ios::sync_with_stdio(false);
    cin.tie(NULL);
    ll t=1;
    cin >> t;
    while(t--){
        solve();
    }
}
