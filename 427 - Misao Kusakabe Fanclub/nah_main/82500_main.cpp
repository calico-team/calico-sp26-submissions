#include <bits/stdc++.h>
using namespace std;
using ll = long long;

void solve(){
    ll n,p,r,k,i,kcount=0;
    cin >> n >> p >> r >> k;
    vector<ll>v(n);
    for(i=0;i<n;i++){
        cin >> v[i];
    }
    for(i=0;i<n;i++){
        p-=v[i];
        if(kcount==k){
            p+=r;
            kcount=0;
        }
        if(p<0){
            cout << "nah i’d lose" << endl;
            return;
        }
        kcount++;
    }
    cout << "nah i’d win" << endl;
}
 
int main(){
    ios::sync_with_stdio(false);
    cin.tie(NULL);
    ll t=1;
    cin >> t;
    while(t--){
        solve();
    }
}
