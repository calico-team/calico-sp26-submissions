def solve():
  p,a,b=map(int,input().split())
  mask=1<<a
  ans=[
    ">>>v...",
    "...v...",
  ]
  if a>0:
    a-=1
    ans.append(".<<S>>.")
    ans.append(".v.^.v.")
    ans.append(".v...v.")
  else:
    b-=1
    ans.append(".<<S>>.")
    ans.append(".v.D.v.")
    ans.append(".v...v.")
  for bit in bin(p)[3:]:
    if bit=="1":
      ans.append(".v...v.")
      ans.append(".v<<<S<")
      ans.append(".v...v.")
    else:
      ans.append(".v...v.")
      ans.append(".v..DS<")
      ans.append(".v...v.")
  ans.append(".>>v.D.")
  ans.append("...v...")
  ans.append("...v...")
  for _ in range(a):
    ans.append(".<<SD..")
    ans.append(".v.^...")
    ans.append(".>>v...")
  for _ in range(b):
    ans.append(".<<SD..")
    ans.append(".v.D...")
    ans.append(".>>v...")
    ans.append("...v...")
  print(len(ans),7)
  print(*ans,sep="\n")
t=1
t=int(input())
for _ in" "*t:
  solve()